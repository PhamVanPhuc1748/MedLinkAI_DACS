# Hợp nhất từ điển (đối với C/F dataset, đôi khi ID có D đầu, hoặc chỉ là số)
ALL_TRANSLATIONS = {}

def init_translations():
    # Thêm bệnh tiếng Anh
    for k, v in DISEASE_EN_VI.items():
        ALL_TRANSLATIONS[k.lower()] = v
    # Thêm bệnh mã OMIM
    for k, v in OMIM_VI.items():
        ALL_TRANSLATIONS[k] = v
        # Đôi khi ID không có chữ D ở đầu trong F-dataset
        if k.startswith("D"):
            ALL_TRANSLATIONS[k[1:]] = v

init_translations()

def translate_disease(name: str) -> str:
    """
    Trả về tên Tiếng Việt của bệnh nếu có, nếu không thì giữ nguyên tên gốc.
    """
    if not name:
        return ""
    
    # Check 1: tên tiếng Anh (lower case)
    lower_name = name.lower().strip()
    if lower_name in ALL_TRANSLATIONS:
        return ALL_TRANSLATIONS[lower_name]
    
    # Check 2: mã OMIM
    key = name.strip()
    if key in ALL_TRANSLATIONS:
        return ALL_TRANSLATIONS[key]
        
    return name

def get_display_name(name: str) -> str:
    """
    Trả về chuỗi hiển thị kết hợp gốc và dịch (ví dụ: 'anxiety disorders (Rối loạn lo âu)').
    Với mã OMIM, thay thế hoàn toàn để UI đẹp hơn, hoặc giữ dạng 'D102100 - Lo âu'.
    """
    if not name:
        return ""
    
    vi_name = translate_disease(name)
    
    if vi_name != name:
        # Nếu là mã OMIM (thường là mã alphanumeric D + số)
        if name.startswith("D") and name[1:].isdigit():
            return f"[{name}] {vi_name}"
        elif name.isdigit():
            return f"[D{name}] {vi_name}"
        # Nếu là tên tiếng Anh
        return f"{name} ({vi_name})"
    
    return name
