def get_viet_name(omim_id: str) -> str:
    """
    Trả về tên Tiếng Việt của mã bệnh OMIM.
    Nếu không tìm thấy, trả về tên tiếng Anh (nếu có) hoặc mã gốc.
    """
    entry = OMIM_DICT.get(omim_id.upper())
    if entry:
        return entry[1]  # Tiếng Việt
    return omim_id  # Fallback: trả về mã gốc


def get_en_name(omim_id: str) -> str:
    """Trả về tên tiếng Anh của mã OMIM."""
    entry = OMIM_DICT.get(omim_id.upper())
    if entry:
        return entry[0]
    return omim_id


def translate_disease_name(name: str) -> str:
    """
    Dịch tên bệnh sang tiếng Việt.
    - Nếu name là mã OMIM (ví dụ D102100) → tra từ điển → trả tiếng Việt
    - Nếu name là tên tiếng Anh thông thường → trả nguyên (B-dataset đã có tên rõ)
    """
    stripped = name.strip()
    # Mã OMIM thường có dạng D + 6 chữ số
    if stripped.upper().startswith("D") and stripped[1:].isdigit() and 5 <= len(stripped) <= 8:
        return get_viet_name(stripped.upper())
    return stripped
